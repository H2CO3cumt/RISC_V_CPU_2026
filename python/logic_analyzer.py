#!/usr/bin/env python3
"""Small dependency-free decoder for the Task 30 Raw capture stream.

The FPGA software emits a text header followed by hexadecimal sample bytes.
The decoder also accepts a plain binary file (one sample byte per record),
decodes UART/SPI from those samples, and writes a standards-compliant VCD.
"""
from __future__ import annotations
import argparse
import re
from pathlib import Path
from typing import Iterable, List, Sequence, Tuple

HEADER = re.compile(rb"LA RAW count=([0-9a-fA-F]{1,8}) trigger=([0-9a-fA-F]{1,8})")

def parse_raw(data: bytes | str, channels: int = 8) -> Tuple[List[int], int | None]:
    """Return masked sample values and trigger index from text or raw bytes."""
    raw = data.encode("ascii", "replace") if isinstance(data, str) else data
    match = HEADER.search(raw)
    if match:
        count = int(match.group(1), 16)
        trigger = int(match.group(2), 16)
        tail = raw[match.end():]
        values = [int(token, 16) for token in re.findall(rb"\b[0-9a-fA-F]{1,8}\b", tail)]
        return [v & ((1 << channels) - 1) for v in values[:count]], trigger
    # Binary fallback deliberately does not guess a textual format.
    return [v & ((1 << channels) - 1) for v in raw], None

def decode_uart(samples: Sequence[int], channel: int = 0, bit_samples: int = 16) -> Tuple[bytes, int]:
    """Decode 8N1 UART from uniformly sampled levels; returns bytes/errors."""
    mask = 1 << channel
    level = [1 if s & mask else 0 for s in samples]
    out = bytearray(); errors = 0; i = 1
    # The falling edge only identifies the start-bit boundary.  Sampling on
    # subsequent bit boundaries works in an ideal simulation but is fragile on
    # a real board because the generated waveform and capture clock can have an
    # arbitrary phase.  Sample each data/stop bit in its centre instead.
    half_bit = max(1, bit_samples // 2)
    while i + bit_samples * 9 + half_bit < len(level):
        if level[i - 1] == 1 and level[i] == 0:
            value = 0
            for bit in range(8):
                value |= level[i + bit_samples * (bit + 1) + half_bit] << bit
            stop = level[i + bit_samples * 9 + half_bit]
            if stop != 1: errors += 1
            else: out.append(value)
            i += bit_samples * 10
        else:
            i += 1
    return bytes(out), errors

def decode_spi(samples: Sequence[int], clock: int = 0, mosi: int = 1, cs: int | None = 2) -> bytes:
    """Decode mode-0 SPI bytes, sampling MOSI on clock rising edges."""
    cm, mm = 1 << clock, 1 << mosi
    csm = 1 << cs if cs is not None else 0
    value = 0; bits = 0; out = bytearray(); previous = 0
    for sample in samples:
        active = cs is None or not (sample & csm)
        rising = not previous and bool(sample & cm)
        previous = 1 if sample & cm else 0
        if active and rising:
            value = ((value << 1) | (1 if sample & mm else 0)) & 0xFF
            bits += 1
            if bits == 8:
                out.append(value); value = 0; bits = 0
        elif not active:
            value = 0; bits = 0
    return bytes(out)

def write_vcd(samples: Sequence[int], path: str | Path, channels: int = 8, trigger: int | None = None) -> None:
    """Write one scalar VCD signal per channel with one time unit per sample."""
    path = Path(path)
    ids = [chr(ord('!') + i) for i in range(channels)]
    with path.open("w", encoding="ascii", newline="\n") as f:
        f.write("$date\n  generated by logic_analyzer.py\n$end\n")
        f.write("$timescale 1ns $end\n$scope module capture $end\n")
        for i, ident in enumerate(ids): f.write(f"$var wire 1 {ident} ch{i} $end\n")
        f.write("$upscope $end\n$enddefinitions $end\n")
        f.write("#0\n")
        for i, ident in enumerate(ids): f.write(f"{(samples[0] >> i) & 1 if samples else 0}{ident}\n")
        for t, sample in enumerate(samples[1:], 1):
            f.write(f"#{t}\n")
            for i, ident in enumerate(ids): f.write(f"{(sample >> i) & 1}{ident}\n")
        if trigger is not None and 0 <= trigger < len(samples):
            f.write(f"$comment trigger_index={trigger} $end\n")

def main(argv: Iterable[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Decode Task 30 Raw capture and export VCD")
    p.add_argument("input", type=Path); p.add_argument("--output-vcd", type=Path)
    p.add_argument("--channels", type=int, default=8); p.add_argument("--uart-channel", type=int)
    p.add_argument("--bit-samples", type=int, default=16); p.add_argument("--spi-clock", type=int)
    p.add_argument("--spi-mosi", type=int, default=1); p.add_argument("--spi-cs", type=int, default=2)
    a = p.parse_args(argv); samples, trigger = parse_raw(a.input.read_bytes(), a.channels)
    print(f"samples={len(samples)} trigger_index={trigger if trigger is not None else 'unknown'}")
    if a.output_vcd: write_vcd(samples, a.output_vcd, a.channels, trigger)
    if a.uart_channel is not None:
        value, errors = decode_uart(samples, a.uart_channel, a.bit_samples)
        print(f"uart={value.hex()} frame_errors={errors}")
    if a.spi_clock is not None:
        print(f"spi={decode_spi(samples, a.spi_clock, a.spi_mosi, a.spi_cs).hex()}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
