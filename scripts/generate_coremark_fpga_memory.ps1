param(
  [int]$Iterations = 1000,
  [int]$ClockHz = 50000000,
  [int]$AutoStart = 0,
  [string]$OutputFile = 'fpga/task28_coremark/rtl/coremark_program_memory.v',
  [string]$MemoryDirectory = 'fpga/task28_coremark/rtl'
)
$ErrorActionPreference='Stop'
if(-not $env:RISCV_PREFIX){$env:RISCV_PREFIX='riscv-none-elf-'}
& make.exe -C software/coremark clean
if($LASTEXITCODE -ne 0){exit $LASTEXITCODE}
& make.exe -C software/coremark all "ITERATIONS=$Iterations" "CLOCK_HZ=$ClockHz" "AUTOSTART=$AutoStart"
if($LASTEXITCODE -ne 0){exit $LASTEXITCODE}

function Read-VerilogWords([string]$Path){
  $result=[ordered]@{}
  [uint32]$index=0
  foreach($token in ((Get-Content -Raw -LiteralPath $Path) -split '\s+')){
    if(-not $token){continue}
    if($token[0] -eq '@'){$index=[Convert]::ToUInt32($token.Substring(1),16);continue}
    if($token -notmatch '^[0-9A-Fa-f]{8}$'){throw "Unexpected memory token '$token' in $Path"}
    $result[[uint32]$index]=$token.ToUpperInvariant()
    $index++
  }
  return $result
}

$imem=Read-VerilogWords 'software/coremark/build/coremark_imem.mem'
$dmem=Read-VerilogWords 'software/coremark/build/coremark_dmem.mem'
if(($imem.Keys | Measure-Object -Maximum).Maximum -ge 8192){throw 'CoreMark IMEM exceeds 32 KiB'}
$drom=[ordered]@{}
foreach($entry in $dmem.GetEnumerator()){
  $address=[uint32]$entry.Key*4
  if($address -lt 0x8000 -or $address -ge 0xc000){throw ('CoreMark initialized data outside DROM: 0x{0:x8}' -f $address)}
  $drom[[uint32]$entry.Key-8192]=$entry.Value
}

# 固定深度镜像让 PDS 识别同步 DRM 模板，也保证未使用存储位确定为零。
$imemImage=[Collections.Generic.List[string]]::new()
for($index=0;$index -lt 8192;$index++){
  $key=[uint32]$index
  $imemImage.Add($(if($imem.Contains($key)){$imem[$key]}else{'00000000'}))
}
$dromImage=[Collections.Generic.List[string]]::new()
for($index=0;$index -lt 4096;$index++){
  $key=[uint32]$index
  $dromImage.Add($(if($drom.Contains($key)){$drom[$key]}else{'00000000'}))
}
$ramImage=[Collections.Generic.List[string]]::new()
for($index=0;$index -lt 4096;$index++){$ramImage.Add('00000000')}
New-Item -ItemType Directory -Force -Path $MemoryDirectory | Out-Null
$imemImage | Set-Content -LiteralPath (Join-Path $MemoryDirectory 'coremark_imem.mem') -Encoding ascii
$dromImage | Set-Content -LiteralPath (Join-Path $MemoryDirectory 'coremark_drom.mem') -Encoding ascii
$ramImage | Set-Content -LiteralPath (Join-Path $MemoryDirectory 'coremark_ram.mem') -Encoding ascii

$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/generate_coremark_fpga_memory.ps1; do not hand edit.')
$lines.Add("// Official CoreMark hardware image: ITERATIONS=$Iterations, CLOCK_HZ=$ClockHz.")
$lines.Add('module coremark_imem(input wire clk,input wire reset,input wire req_valid,output wire req_ready,input wire [31:0] req_addr,output reg rsp_valid,input wire rsp_ready,output reg [31:0] rsp_data,output reg rsp_error);')
$lines.Add(" reg [31:0] mem[0:8191]; wire address_ok=(req_addr[1:0]==2'b00)&&(req_addr<32'h0000_8000); assign req_ready=!rsp_valid;")
$lines.Add(' initial begin')
$lines.Add('`ifdef COREMARK_SIM')
$lines.Add('  $readmemh("fpga/task28_coremark/rtl/coremark_imem.mem",mem);')
$lines.Add('`else')
$lines.Add('  $readmemh("rtl/coremark_imem.mem",mem);')
$lines.Add('`endif')
$lines.Add(' end')
$lines.Add(" always @(posedge clk) begin if(reset) begin rsp_valid<=0;rsp_data<=0;rsp_error<=0;end else if(req_valid&&req_ready) begin rsp_valid<=1;rsp_error<=!address_ok;rsp_data<=address_ok?mem[req_addr[14:2]]:0;end else if(rsp_valid&&rsp_ready) rsp_valid<=0; end")
$lines.Add('endmodule')
$lines.Add('')
$lines.Add('module coremark_dmem(input wire clk,input wire reset,output wire init_done,input wire req_valid,output wire req_ready,input wire [31:0] req_addr,input wire req_write,input wire [31:0] req_wdata,input wire [3:0] req_wstrb,output reg rsp_valid,input wire rsp_ready,output reg [31:0] rsp_rdata,output reg rsp_error);')
$lines.Add(' reg [31:0] drom[0:4095]; reg [31:0] ram[0:4095];')
$lines.Add(" wire drom_hit=req_addr>=32'h0000_8000&&req_addr<32'h0000_c000; wire ram_hit=req_addr>=32'h0000_c000&&req_addr<32'h0001_0000;")
$lines.Add(" assign init_done=1'b1; assign req_ready=!rsp_valid;")
$lines.Add(' initial begin')
$lines.Add('`ifdef COREMARK_SIM')
$lines.Add('  $readmemh("fpga/task28_coremark/rtl/coremark_drom.mem",drom);')
$lines.Add('  $readmemh("fpga/task28_coremark/rtl/coremark_ram.mem",ram);')
$lines.Add('`else')
$lines.Add('  $readmemh("rtl/coremark_drom.mem",drom);')
$lines.Add('  $readmemh("rtl/coremark_ram.mem",ram);')
$lines.Add('`endif')
$lines.Add(' end')
$lines.Add(' always @(posedge clk) begin')
$lines.Add("  if(reset) begin rsp_valid<=0;rsp_rdata<=0;rsp_error<=0;end")
$lines.Add('  else begin')
$lines.Add("   if(req_valid&&req_ready) begin rsp_valid<=1;rsp_error<=(!drom_hit&&!ram_hit)||(req_write&&drom_hit);if(req_write&&ram_hit) begin if(req_wstrb[0])ram[req_addr[13:2]][7:0]<=req_wdata[7:0];if(req_wstrb[1])ram[req_addr[13:2]][15:8]<=req_wdata[15:8];if(req_wstrb[2])ram[req_addr[13:2]][23:16]<=req_wdata[23:16];if(req_wstrb[3])ram[req_addr[13:2]][31:24]<=req_wdata[31:24];rsp_rdata<=0;end else if(!req_write&&ram_hit)rsp_rdata<=ram[req_addr[13:2]];else if(!req_write&&drom_hit)rsp_rdata<=drom[(req_addr-32'h0000_8000)>>2];else rsp_rdata<=0;end else if(rsp_valid&&rsp_ready)rsp_valid<=0;")
$lines.Add('  end')
$lines.Add(' end')
$lines.Add('endmodule')
$parent=Split-Path -Parent $OutputFile
New-Item -ItemType Directory -Force -Path $parent | Out-Null
$lines | Set-Content -LiteralPath $OutputFile -Encoding ascii
Write-Host "COREMARK FPGA MEMORY GENERATED iterations=$Iterations autostart=$AutoStart imem_words=$($imem.Count) drom_words=$($drom.Count) output=$OutputFile"
