param(
  [int]$Depth=1024,
  [int]$AutoStart=0,
  # 镜像容量档位（2026-10-24 新增）：默认 4 KB，与交付工程完全一致。
  # 8 表示用 link8k.ld + -DRAM_KB=8（start.S 的栈顶抬到 0x2000），只有 tr85 那档
  # 演示位流需要——它的 0xAB 组合命令在 4 KB 镜像里装不下（实测溢出 436 字节）。
  # 必须与 $Depth 配对：4 KB↔1024、8 KB↔2048；不配对会静默踩坏栈。
  [int]$RamKb=4,
  # 输出目录：默认是 50 MHz 交付工程 fpga/logic_analyzer/rtl。
  # 85 MHz 变体有自己的副本（fpga/logic_analyzer_85m/rtl），生成时用这个参数指过去，
  # 否则 85 MHz 工程会继续用旧固件，而波形看起来"也是对的"，很难查。
  [string]$MemoryDirectory='fpga/logic_analyzer/rtl',
  # `ifdef LOGIC_ANALYZER_SIM 分支里 $readmemh 的目录（仿真专用；PDS 走 rtl/ 相对路径）。
  [string]$SimDirectory='fpga/logic_analyzer/rtl'
)
$ErrorActionPreference='Stop'
if($RamKb -ne 4 -and ($RamKb * 256) -ne $Depth){throw "RamKb=$RamKb 与 Depth=$Depth 不配对（4 KB↔1024、8 KB↔2048）"}
if(-not $env:RISCV_PREFIX){$env:RISCV_PREFIX='riscv-none-elf-'}
# make/gcc 会把 ld 的 "LOAD segment with RWX permissions" 警告写到 **stderr**。
# 在 Windows PowerShell 5.1 里，原生命令的 stderr 会被包成 ErrorRecord，而本脚本是
# $ErrorActionPreference='Stop' —— 于是这条**警告**会把脚本就地打停（表现为外部
# 只看到 gcc 命令行 + 警告，之后什么都没有，退出码 1）。
# 2026-10-21 实测：同一个脚本单独跑能过、在 run_final_regression 里跑就停在这一步，
# 差别只在错误动作的作用域。修法与 run_final_regression.ps1 里既有的做法一致：
# 调用原生命令期间放开错误动作，成败一律以 $LASTEXITCODE 判定。
$prevEap=$ErrorActionPreference
$ErrorActionPreference='Continue'
$makeArgs=@('-C','software/logic_analyzer','clean')
try {
  & make.exe @makeArgs
  $code=$LASTEXITCODE
  if($code -eq 0){
    # 4 KB 档不传任何容量相关变量，命令行与历史完全一致（保证交付镜像逐字节不变）
    if($RamKb -eq 4){
      & make.exe -C software/logic_analyzer all "AUTOSTART=$AutoStart"
    } else {
      & make.exe -C software/logic_analyzer all "AUTOSTART=$AutoStart" "RAM_KB=$RamKb" "LINKER_SCRIPT=link$($RamKb)k.ld"
    }
    $code=$LASTEXITCODE
  }
} finally {
  $ErrorActionPreference=$prevEap
}
if($code -ne 0){exit $code}
$words=[Collections.Generic.List[string]]::new()
for($i=0;$i -lt $Depth;$i++){$words.Add('00000000')}
[uint32]$index=0
foreach($token in ((Get-Content -Raw software/logic_analyzer/build/logic_analyzer.mem)-split '\s+')){
 if(-not $token){continue}
 if($token[0]-eq '@'){$index=[Convert]::ToUInt32($token.Substring(1),16);continue}
 if($token -notmatch '^[0-9A-Fa-f]{2,8}$' -or ($token.Length%2)-ne 0){throw "Unexpected logic-analyzer image token '$token'"}
 if($index -ge $Depth){throw "Logic-analyzer image exceeds $($Depth*4) bytes"}
 $words[[int]$index]=$token.PadLeft(8,'0').ToUpperInvariant();$index++
}
$dir=$MemoryDirectory;$words|Set-Content "$dir/logic_analyzer_program.mem" -Encoding ascii
$rtl=@'
// Generated by scripts/generate_logic_analyzer_fpga_memory.ps1; do not hand edit.
// 取指 ready 允许“响应被接收的同一拍接收下一笔请求”，使 Core 取指达到每拍一条；
// 数据端口 logic_analyzer_dmem 由 dstate 串行化，保持 !rsp_valid 不变。
module logic_analyzer_imem #(parameter DEPTH=1024)(input wire clk,input wire reset,input wire req_valid,output wire req_ready,input wire [31:0] req_addr,output reg rsp_valid,input wire rsp_ready,output reg [31:0] rsp_data,output reg rsp_error);
 reg [31:0] mem[0:DEPTH-1];wire address_ok=(req_addr[1:0]==0)&&(req_addr[31:2]<DEPTH);assign req_ready=!rsp_valid||rsp_ready;
 initial begin
`ifdef LOGIC_ANALYZER_SIM
  $readmemh("__SIMDIR__/logic_analyzer_program.mem",mem);
`else
  $readmemh("rtl/logic_analyzer_program.mem",mem);
`endif
 end
 always @(posedge clk)begin if(reset)begin rsp_valid<=0;rsp_data<=0;rsp_error<=0;end else if(req_valid&&req_ready)begin rsp_valid<=1;rsp_error<=!address_ok;rsp_data<=address_ok?mem[req_addr[11:2]]:0;end else if(rsp_valid&&rsp_ready)rsp_valid<=0;end
endmodule
module logic_analyzer_dmem #(parameter DEPTH=1024)(input wire clk,input wire reset,input wire req_valid,output wire req_ready,input wire [31:0] req_addr,input wire req_write,input wire [31:0] req_wdata,input wire [3:0] req_wstrb,output reg rsp_valid,input wire rsp_ready,output reg [31:0] rsp_rdata,output reg rsp_error);
 reg [31:0] mem[0:DEPTH-1];wire address_ok=req_addr[31:2]<DEPTH;assign req_ready=!rsp_valid;
 initial begin
`ifdef LOGIC_ANALYZER_SIM
  $readmemh("__SIMDIR__/logic_analyzer_program.mem",mem);
`else
  $readmemh("rtl/logic_analyzer_program.mem",mem);
`endif
 end
 always @(posedge clk)begin if(reset)begin rsp_valid<=0;rsp_rdata<=0;rsp_error<=0;end else if(req_valid&&req_ready)begin rsp_valid<=1;rsp_error<=!address_ok;if(address_ok&&req_write)begin if(req_wstrb[0])mem[req_addr[11:2]][7:0]<=req_wdata[7:0];if(req_wstrb[1])mem[req_addr[11:2]][15:8]<=req_wdata[15:8];if(req_wstrb[2])mem[req_addr[11:2]][23:16]<=req_wdata[23:16];if(req_wstrb[3])mem[req_addr[11:2]][31:24]<=req_wdata[31:24];rsp_rdata<=0;end else rsp_rdata<=address_ok?mem[req_addr[11:2]]:0;end else if(rsp_valid&&rsp_ready)rsp_valid<=0;end
endmodule
'@
$rtl=$rtl.Replace('__SIMDIR__',$SimDirectory)
# 深度与索引位宽必须配对：DEPTH=1024 → 1024 个字 = 10 位 → req_addr[11:2]；
# DEPTH=2048 → 11 位 → req_addr[12:2]。高位下标 = log2(DEPTH) + 1。
# 对 1024 这两处替换都是空操作，因此**默认档生成的文本逐字节不变**（交付工程走这条）。
# 2026-10-24 踩过这里的错：写成 log2(DEPTH)-1 会得到 req_addr[10:2]（9 位），
# 2048 深的存储器只认 256 个字 → 取指全部别名 → CPU 跑飞、串口只剩噪声（板级与仿真同时复现）。
$addrHi=[int][Math]::Log($Depth,2)+1
$rtl=$rtl.Replace('parameter DEPTH=1024',"parameter DEPTH=$Depth")
$rtl=$rtl.Replace('req_addr[11:2]',"req_addr[$($addrHi):2]")
$rtl|Set-Content "$dir/logic_analyzer_program_memory.v" -Encoding ascii
Write-Host "LOGIC ANALYZER FPGA MEMORY GENERATED depth=$Depth ramkb=$RamKb autostart=$AutoStart used_words=$index"
