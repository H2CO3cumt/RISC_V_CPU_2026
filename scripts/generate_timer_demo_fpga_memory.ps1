param(
  [int]$Depth = 1024,
  # 交付镜像的 delta（拍）：12_500_000 在 50 MHz 下正好 0.25 s。
  # 配合 -TestDelta 时这是**仿真**用的 delta（要明显大于 ISR 长度，见 run_timer_demo_board_top_tb.ps1）。
  [int]$Delta = 12500000,
  # 额外的固件编译宏，原样传给 make 的 EXTRA_DEFINE（例如
  # '-DTIMER_DEMO_MINIMAL_UART=1' 用来做"ISR 只发 1 个字节"的对照实验）。
  # 交付镜像留空。
  [string]$ExtraDefine = '',
  [switch]$TestDelta
)
# N1 板级中断演示的取指/数据镜像生成器。
#
# 为什么要有这个脚本（而不是直接用 tb/data/timer_irq.mem）：
#   1. 板级镜像必须覆盖**整个取指窗口**（RAM aperture 0x0000_0fff = 1024 字）。Core 在
#      Trap 相关的用例里会顺序取到程序区之外的地址，那些字必须是**确定**的值：
#      这里统一填 `jal x0,0` 自跳转，避免取到 0 字（=非法指令）又被精确陷入、
#      把 PC 交给 mtvec 默认值 0 从而**静默重启程序**。这一条是既有 Testbench 踩过的坑
#      （见 tb/pipeline_imem_adapter.v 的 FILL_WORD 注释）。
#   2. `fpga/timer_demo/rtl/timer_demo_program_memory.v` 里 IMEM 与 DMEM 共用同一份
#      BRAM 镜像，PC 直接当 DMEM 索引用（见该文件注释）。生成器保证 imem/dmem 内容一致。
#   3. 交付镜像的 delta 必须是**真实值**（12_500_000 拍 = 50 MHz 下 0.25 s）。
#      仿真用的小 delta 由 -TestDelta 单独生成，绝不写回交付镜像。
$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$swDir = Join-Path $repo 'software/timer_demo'
$outDir = Join-Path $repo 'fpga/timer_demo/rtl'

# make/ninja 之外的依赖：RISCV_PREFIX 由用户环境变量统一给出（工程统一规定）。
# 当前 shell 里可能没继承到，缺省补成项目固定前缀，构建脚本里不硬编码完整路径。
if (-not $env:RISCV_PREFIX) { $env:RISCV_PREFIX = 'riscv-none-elf-' }

# ---------------------------------------------------------------- 1) 编译固件
$makeArgs = @('-C', 'software/timer_demo', 'clean')
& make.exe @makeArgs
if ($LASTEXITCODE -ne 0) { throw 'timer_demo: make clean failed' }

$makeArgs = @('-C', 'software/timer_demo', 'all', "DELTA=$Delta")
if ($ExtraDefine) { $makeArgs += "EXTRA_DEFINE=$ExtraDefine" }
# -TestDelta 只是"这次生成的是仿真镜像"的标记（用于输出与文档说明）：
# delta 的具体数值**只有一个来源**，就是上面的 -Delta。
# 早先版本在这里另写了一个常量 2000，结果把调用方传进来的 -Delta 覆盖掉，
# 生成了 delta 与 Testbench 不一致的镜像——所以这个分支被删掉了。
$effectiveDelta = $Delta
& make.exe @makeArgs
if ($LASTEXITCODE -ne 0) { throw 'timer_demo: make all failed' }

# ------------------------------------------------- 2) 解析 objcopy 的 verilog 镜像
# objcopy -O verilog 的输出形如：
#   @00000000
#   100037B7 100005B7 ...
# 用 '@' 记号处理稀疏布局，其余 token 必须是 2/4/8 个十六进制位（字节对齐）。
$words = [Collections.Generic.List[string]]::new()
for ($i = 0; $i -lt $Depth; $i++) { $words.Add('0000006F') }   # 程序区之外 = jal x0,0
[uint32]$index = 0
$imageFile = Join-Path $swDir 'build/timer_demo.mem'
foreach ($token in ((Get-Content -Raw $imageFile) -split '\s+')) {
  if (-not $token) { continue }
  if ($token[0] -eq '@') { $index = [Convert]::ToUInt32($token.Substring(1), 16); continue }
  if ($token -notmatch '^[0-9A-Fa-f]{2,8}$' -or ($token.Length % 2) -ne 0) {
    throw "Unexpected timer-demo image token '$token'"
  }
  if ($index -ge $Depth) { throw "timer-demo image exceeds $($Depth*4) bytes (index=$index)" }
  $words[[int]$index] = $token.PadLeft(8, '0').ToUpperInvariant()
  $index++
}
$usedWords = $index

# ------------------------------------------------------------- 3) 写镜像与 RTL
New-Item -ItemType Directory -Force $outDir | Out-Null
$memPath = Join-Path $outDir 'timer_demo_program.mem'
$words | Set-Content $memPath -Encoding ascii

# 生成式 RTL，与 fpga/logic_analyzer/rtl/logic_analyzer_program_memory.v 同一模式：
#   - imem 的 req_ready 允许"响应被接收的同一拍接收下一笔请求"（取指满速）；
#   - dmem 串行化（req_ready = !rsp_valid），与互连的单 outstanding 约定一致；
#   - $readmemh 放在 initial 里：PDS 的 compile 阶段**支持**这种写法并会真正加载
#     （实测日志 `Loading memory data from file .../timer_demo_program.mem`），
#     不能用 rtl/soc_fpga_memory.v 那种"综合不消费 $readmemh"的老结论去套。
$rtl = @'
// Generated by scripts/generate_timer_demo_fpga_memory.ps1; do not hand edit.
//
// 为什么 IMEM 与 DMEM 用**同一份**镜像：
//   本演示程序把只读字符表放在 .rodata 里，用 lbu 从 .rodata 地址读字符，
//   而那条 lbu 走的是 Core 的**数据端口**（DMEM），取指走的是**取指端口**（IMEM）。
//   两个 BRAM 若各自初始化不同内容，"取到的指令"和"读到的常量"就对不上。
//   既有交付工程 fpga/logic_analyzer 用的是同一个办法（它的 dmem 也加载同一份 program.mem），
//   这里保持完全一致，不引入新的存储结构。
//
// 端口语义与 docs/interfaces.md §2.2 一致：单 outstanding、valid/ready 握手、
// 未映射地址返回 rsp_error 而不是静默给 0。
module timer_demo_imem #(parameter DEPTH=1024)(input wire clk,input wire reset,input wire req_valid,output wire req_ready,input wire [31:0] req_addr,output reg rsp_valid,input wire rsp_ready,output reg [31:0] rsp_data,output reg rsp_error);
 reg [31:0] mem[0:DEPTH-1];wire address_ok=(req_addr[1:0]==0)&&(req_addr[31:2]<DEPTH);assign req_ready=!rsp_valid||rsp_ready;
 initial begin
`ifdef TIMER_DEMO_SIM
  $readmemh("fpga/timer_demo/rtl/timer_demo_program.mem",mem);
`else
  $readmemh("rtl/timer_demo_program.mem",mem);
`endif
 end
 always @(posedge clk)begin if(reset)begin rsp_valid<=0;rsp_data<=0;rsp_error<=0;end else if(req_valid&&req_ready)begin rsp_valid<=1;rsp_error<=!address_ok;rsp_data<=address_ok?mem[req_addr[11:2]]:0;end else if(rsp_valid&&rsp_ready)rsp_valid<=0;end
endmodule
module timer_demo_dmem #(parameter DEPTH=1024)(input wire clk,input wire reset,input wire req_valid,output wire req_ready,input wire [31:0] req_addr,input wire req_write,input wire [31:0] req_wdata,input wire [3:0] req_wstrb,output reg rsp_valid,input wire rsp_ready,output reg [31:0] rsp_rdata,output reg rsp_error);
 reg [31:0] mem[0:DEPTH-1];wire address_ok=req_addr[31:2]<DEPTH;assign req_ready=!rsp_valid;
 initial begin
`ifdef TIMER_DEMO_SIM
  $readmemh("fpga/timer_demo/rtl/timer_demo_program.mem",mem);
`else
  $readmemh("rtl/timer_demo_program.mem",mem);
`endif
 end
 always @(posedge clk)begin if(reset)begin rsp_valid<=0;rsp_rdata<=0;rsp_error<=0;end else if(req_valid&&req_ready)begin rsp_valid<=1;rsp_error<=!address_ok;if(address_ok&&req_write)begin if(req_wstrb[0])mem[req_addr[11:2]][7:0]<=req_wdata[7:0];if(req_wstrb[1])mem[req_addr[11:2]][15:8]<=req_wdata[15:8];if(req_wstrb[2])mem[req_addr[11:2]][23:16]<=req_wdata[23:16];if(req_wstrb[3])mem[req_addr[11:2]][31:24]<=req_wdata[31:24];rsp_rdata<=0;end else rsp_rdata<=address_ok?mem[req_addr[11:2]]:0;end else if(rsp_valid&&rsp_ready)rsp_valid<=0;end
endmodule
'@
$rtl | Set-Content (Join-Path $outDir 'timer_demo_program_memory.v') -Encoding ascii

Write-Host "TIMER DEMO FPGA MEMORY GENERATED depth=$Depth delta=$effectiveDelta test_delta=$($TestDelta.IsPresent) used_words=$usedWords"
Write-Host "  image : $memPath"
Write-Host "  rtl   : $(Join-Path $outDir 'timer_demo_program_memory.v')"
